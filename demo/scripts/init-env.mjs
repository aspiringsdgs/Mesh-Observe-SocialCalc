// Generates throwaway TESTNET wallets and the local env files. Never overwrites existing files.
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import bs58 from 'bs58'
import nacl from 'tweetnacl'
import { generatePrivateKey, privateKeyToAccount } from 'viem/accounts'

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..')
const at = (...p) => path.join(ROOT, ...p)
const writeNew = (file, content) => {
  if (fs.existsSync(file)) return console.log(`keep    ${path.relative(ROOT, file)}`)
  fs.writeFileSync(file, typeof content === 'function' ? content() : content, { mode: 0o600 })
  console.log(`create  ${path.relative(ROOT, file)}`)
}

const walletsFile = at('demo/wallets.local.json')
if (!fs.existsSync(walletsFile)) {
  const sol = () => { const k = nacl.sign.keyPair(); return { publicKey: bs58.encode(k.publicKey), secretKey: Array.from(k.secretKey) } }
  const evm = () => { const privateKey = generatePrivateKey(); return { address: privateKeyToAccount(privateKey).address, privateKey } }
  writeNew(walletsFile, JSON.stringify({
    note: 'TESTNET-ONLY throwaway keys generated for the local demo. Never fund on mainnet.',
    solanaAdmin: sol(), solanaUser: sol(), baseTreasury: evm(), baseAgent: evm(),
  }, null, 2))
}
const w = JSON.parse(fs.readFileSync(walletsFile, 'utf8'))
const idl = JSON.stringify(JSON.parse(fs.readFileSync(at('afara/server/src/utils/solana/idl.json'), 'utf8')))

writeNew(at('afara/server/.env'), () => `# Local demo config (testnet only) — generated by demo/scripts/init-env.mjs, do not commit
PORT=5040
NODE_ENV=development
DATABASE_URL="postgres://postgres:postgres@db.localtest.me:55432/toju"
SOLANA_RPC_URL="https://api.testnet.solana.com"
PROGRAM_ID="${JSON.parse(idl).address}"
SOLANA_PROGRAM_IDL='${idl}'
ADMIN_KEYPAIR='[${w.solanaAdmin.secretKey.join(',')}]'
ADMIN_API_KEY="local-dev-admin-key"
FILECOIN_NETWORK=calibration
# Not used in the demo flows; placeholders only so the server's env check passes
QSTASH_CURRENT_SIGNING_KEY="local-placeholder"
QSTASH_NEXT_SIGNING_KEY="local-placeholder"
RESEND_API_KEY="re_local_placeholder"
EMAIL_FROM="toju local <noreply@example.com>"
EMAIL_REPLY_TO="noreply@example.com"
# x402 agent payments: Base Sepolia, public x402.org facilitator
X402_NETWORK=sepolia
BASE_USDC_WALLET="${w.baseTreasury.address}"
# REQUIRED for IPFS pinning — fill these in (https://app.pinata.cloud)
PINATA_JWT="REPLACE_ME"
PINATA_GATEWAY="https://REPLACE_ME.mypinata.cloud"
`)

writeNew(at('afara/ui/.env.local'), `# Local demo: UI -> local API, Solana testnet
VITE_API_URL=http://localhost:5040
VITE_SOLANA_NETWORK=testnet
VITE_FILECOIN_NETWORK=calibration
`)

writeNew(at('demo/agent/.env'), `# Local demo agent config (Base Sepolia testnet only)
TOJU_ENDPOINT=http://localhost:5040
AGENT_PRIVATE_KEY=${w.baseAgent.privateKey}
# Optional — set ONE of these to drive the agent with an LLM (LangChain). Without it, use direct.mjs.
GROQ_API_KEY=
ANTHROPIC_API_KEY=
OPENAI_API_KEY=
# Optional model override, e.g. groq:openai/gpt-oss-120b, anthropic:claude-sonnet-5-5, openai:gpt-4o
AGENT_MODEL=
`)

console.log(`
Fund these (testnet only):
  Solana TESTNET SOL   ${w.solanaUser.publicKey}      https://faucet.solana.com  (choose Testnet, not Devnet)
  Base Sepolia USDC    ${w.baseAgent.address}   https://faucet.circle.com
Then put your Pinata JWT + gateway into afara/server/.env`)
